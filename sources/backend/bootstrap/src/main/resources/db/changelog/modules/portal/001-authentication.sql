CREATE TABLE AI_PORTAL_SESSION (
    PRIMARY_ID character(36) NOT NULL,
    SESSION_ID character(36) NOT NULL,
    CREATION_TIME bigint NOT NULL,
    LAST_ACCESS_TIME bigint NOT NULL,
    MAX_INACTIVE_INTERVAL integer NOT NULL,
    EXPIRY_TIME bigint NOT NULL,
    PRINCIPAL_NAME character varying(100),
    CONSTRAINT PK_PORTAL_SESSION PRIMARY KEY (PRIMARY_ID)
);
CREATE UNIQUE INDEX UX_PORTAL_SESSION_ID ON AI_PORTAL_SESSION (SESSION_ID);
CREATE INDEX IX_PORTAL_SESSION_EXPIRY ON AI_PORTAL_SESSION (EXPIRY_TIME);
CREATE INDEX IX_PORTAL_SESSION_PRINCIPAL ON AI_PORTAL_SESSION (PRINCIPAL_NAME);
CREATE TABLE AI_PORTAL_SESSION_ATTRIBUTES (
    SESSION_PRIMARY_ID character(36) NOT NULL,
    ATTRIBUTE_NAME character varying(200) NOT NULL,
    ATTRIBUTE_BYTES bytea NOT NULL,
    CONSTRAINT PK_PORTAL_SESSION_ATTR PRIMARY KEY (SESSION_PRIMARY_ID, ATTRIBUTE_NAME),
    CONSTRAINT FK_PORTAL_SESSION_ATTR FOREIGN KEY (SESSION_PRIMARY_ID) REFERENCES AI_PORTAL_SESSION (PRIMARY_ID) ON DELETE CASCADE
);
CREATE TABLE AI_PORTAL_LOGIN_CHALLENGE (
    CHALLENGE_ID character(36) NOT NULL,
    SOURCE_KEY character varying(100) NOT NULL,
    STATE_DIGEST character(64) NOT NULL,
    BROWSER_BIND_DIGEST character(64) NOT NULL,
    NONCE_DIGEST character(64) NOT NULL,
    RETURN_PATH character varying(500) NOT NULL,
    CREATED_DTM timestamp with time zone NOT NULL,
    EXPIRES_DTM timestamp with time zone NOT NULL,
    CONSUMED_DTM timestamp with time zone,
    CONSTRAINT PK_PORTAL_LOGIN_CHALLENGE PRIMARY KEY (CHALLENGE_ID),
    CONSTRAINT UX_PORTAL_LOGIN_STATE UNIQUE (STATE_DIGEST),
    CONSTRAINT CK_PORTAL_LOGIN_EXPIRY CHECK (EXPIRES_DTM > CREATED_DTM)
);
CREATE INDEX IX_PORTAL_LOGIN_EXPIRY ON AI_PORTAL_LOGIN_CHALLENGE (EXPIRES_DTM);
CREATE TABLE AI_PORTAL_AUTH_EVIDENCE (
    SOURCE_KEY character varying(100) NOT NULL,
    EVIDENCE_DIGEST character(64) NOT NULL,
    CHALLENGE_ID character(36) NOT NULL,
    PORTAL_USER_ID bigint NOT NULL,
    CONSUMED_DTM timestamp with time zone NOT NULL,
    EXPIRES_DTM timestamp with time zone NOT NULL,
    CONSTRAINT PK_PORTAL_AUTH_EVIDENCE PRIMARY KEY (SOURCE_KEY, EVIDENCE_DIGEST),
    CONSTRAINT UX_PORTAL_EVIDENCE_CHALLENGE UNIQUE (CHALLENGE_ID),
    CONSTRAINT CK_PORTAL_EVIDENCE_EXPIRY CHECK (EXPIRES_DTM > CONSUMED_DTM)
);
CREATE INDEX IX_PORTAL_EVIDENCE_EXPIRY ON AI_PORTAL_AUTH_EVIDENCE (EXPIRES_DTM);
CREATE TABLE AI_PORTAL_AUTH_EVENT (
    AUTH_EVENT_ID bigint NOT NULL,
    EVENT_KEY character(36) NOT NULL,
    EVENT_TYPE character varying(40) NOT NULL,
    PORTAL_USER_ID bigint,
    AUTH_MODE character varying(10) NOT NULL,
    RESULT_CODE character varying(60) NOT NULL,
    REQUEST_TRACE_ID character varying(100) NOT NULL,
    OCCURRED_DTM timestamp with time zone NOT NULL,
    RECORDED_DTM timestamp with time zone NOT NULL,
    CONSTRAINT PK_PORTAL_AUTH_EVENT PRIMARY KEY (AUTH_EVENT_ID),
    CONSTRAINT UX_PORTAL_AUTH_EVENT_KEY UNIQUE (EVENT_KEY),
    CONSTRAINT CK_PORTAL_AUTH_EVENT_MODE CHECK (AUTH_MODE IN ('LOCAL','EXTERNAL'))
);
CREATE INDEX IX_PORTAL_AUTH_EVENT_TIME ON AI_PORTAL_AUTH_EVENT (OCCURRED_DTM);
CREATE INDEX IX_PORTAL_AUTH_EVENT_USER ON AI_PORTAL_AUTH_EVENT (PORTAL_USER_ID, OCCURRED_DTM);
